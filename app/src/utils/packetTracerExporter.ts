/**
 * Intelligent parser that extracts network devices, interfaces, IP addresses,
 * and Cisco IOS blocks from markdown AI chat responses.
 */
export function parseAiResponseToTopology(text: string, title?: string): NetworkTopology {
  const devicesMap = new Map<string, NetworkDevice>();
  const links: NetworkLink[] = [];

  // 1. Look for device code blocks like:
  // ```ios [R1]
  // or ```cisco R1
  // or ### R1 (Router)
  // or Router# configure terminal
  const codeBlockRegex = /```(?:ios|cisco|bash|plaintext)?\s*(?:\[?([A-Za-z0-9_-]+)\]?)?\n([\s\S]*?)```/gi;
  let match: RegExpExecArray | null;

  while ((match = codeBlockRegex.exec(text)) !== null) {
    const rawTag = match[1] || '';
    const code = match[2];

    // Try finding hostname in code
    const hostnameMatch = code.match(/hostname\s+([A-Za-z0-9_-]+)/i);
    const deviceName = rawTag || (hostnameMatch ? hostnameMatch[1] : null);

    if (deviceName && deviceName.trim().length > 0) {
      const cleanName = deviceName.trim();
      const devType: NetworkDevice['type'] = cleanName.toLowerCase().startsWith('sw') || cleanName.toLowerCase().includes('switch') 
        ? 'switch' 
        : cleanName.toLowerCase().startsWith('pc') 
        ? 'pc' 
        : cleanName.toLowerCase().startsWith('srv') || cleanName.toLowerCase().includes('server')
        ? 'server'
        : 'router';

      const model = devType === 'router' ? 'Cisco 2911' : devType === 'switch' ? 'Cisco 2960-24TT' : 'Generic-PC';

      if (!devicesMap.has(cleanName)) {
        devicesMap.set(cleanName, {
          id: cleanName,
          name: cleanName,
          type: devType,
          model,
          x: 100 + devicesMap.size * 180,
          y: devType === 'router' ? 120 : devType === 'switch' ? 260 : 380,
          interfaces: [],
          iosConfig: code,
        });
      } else {
        const existing = devicesMap.get(cleanName)!;
        existing.iosConfig += '\n' + code;
      }
    }
  }

  // 2. Extract interfaces and IPs from configs
  devicesMap.forEach((device) => {
    const ifaceRegex = /interface\s+([A-Za-z0-9\/\.-]+)([\s\S]*?)(?=(?:interface|\n!|\nend|$))/gi;
    let ifMatch: RegExpExecArray | null;

    while ((ifMatch = ifaceRegex.exec(device.iosConfig)) !== null) {
      const ifaceName = ifMatch[1].trim();
      const body = ifMatch[2];

      const ipMatch = body.match(/ip\s+address\s+([0-9\.]+)\s+([0-9\.]+)/i);
      const ipAddress = ipMatch ? ipMatch[1] : undefined;
      const subnetMask = ipMatch ? ipMatch[2] : undefined;

      const vlanMatch = body.match(/encapsulation\s+dot1Q\s+(\d+)/i) || body.match(/switchport\s+access\s+vlan\s+(\d+)/i);
      const vlan = vlanMatch ? parseInt(vlanMatch[1], 10) : undefined;

      // Avoid duplicates
      if (!device.interfaces.some(i => i.name.toLowerCase() === ifaceName.toLowerCase())) {
        device.interfaces.push({
          name: ifaceName,
          shortName: simplifyInterfaceName(ifaceName),
          ipAddress,
          subnetMask,
          vlan,
          status: 'up',
        });
      }
    }
  });

  // 3. Fallback: if no devices were parsed from code blocks, try scanning common router/switch mentions
  if (devicesMap.size === 0) {
    const defaultTopology = generateDefaultTopology(title || 'Topología de Red Cisco');
    return defaultTopology;
  }

  // 4. Generate logical links between devices
  const devList = Array.from(devicesMap.values());
  for (let i = 0; i < devList.length - 1; i++) {
    const current = devList[i];
    const next = devList[i + 1];
    links.push({
      id: `link_${current.id}_${next.id}`,
      sourceDevice: current.id,
      sourcePort: current.interfaces[0]?.shortName || 'Gi0/0',
      targetDevice: next.id,
      targetPort: next.interfaces[0]?.shortName || 'Gi0/1',
      type: current.type === 'router' && next.type === 'router' ? 'serial' : 'straight',
    });
  }

  return {
    id: 'topo_' + Date.now(),
    name: title || 'Topología de Red Cisco Packet Tracer',
    description: 'Generada a partir de los requerimientos y comandos analizados por NetPilot AI.',
    packetTracerVersion: '8.2.1',
    devices: devList,
    links,
  };
}

function simplifyInterfaceName(name: string): string {
  return name
    .replace(/GigabitEthernet/i, 'Gi')
    .replace(/FastEthernet/i, 'Fa')
    .replace(/Serial/i, 'Se')
    .replace(/Loopback/i, 'Lo');
}


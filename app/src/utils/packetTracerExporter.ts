  readme += `Fecha de creacion: ${new Date().toLocaleString()}\n\n`;
  readme += `OPCIONES DE USO EN CISCO PACKET TRACER:\n\n`;
  readme += `OPCION A (Carga Directa):\n`;
  readme += `1. Abre Cisco Packet Tracer.\n`;
  readme += `2. Ve a File -> Open y selecciona el archivo "${baseName}.pkt" incluido.\n\n`;
  readme += `OPCION B (Pegado rapido en CLI):\n`;
  readme += `1. Abre tu topologia en Packet Tracer.\n`;
